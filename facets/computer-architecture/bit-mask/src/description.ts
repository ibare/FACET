export const bitMaskDescription = `
## 필요한 자리만 남긴다

한 바이트 안에 여러 가지가 함께 들어 있을 때가 있다. 위 넉 자리에 하나,
아래 넉 자리에 또 하나. 그중 하나만 꺼내 보려면 나머지를 **없는 것으로 만들어야**
한다. 지우는 것이 아니라 가리는 것이다.

AND 가 그 일을 한다. 자리마다 **둘 다 1 일 때만 1** 이므로, 상대가 0 인 자리는
원래 값이 무엇이든 0 이 된다. 그러니 짝으로 놓는 수를 덮개로 읽어도 된다 —
**1 이 구멍이고 0 이 가림막이다.** 그 덮개를 마스크라고 부른다.

{facet:bitMask}

## 여덟 자리가 서로를 모른다

그림에서 덮개는 한 장이고 한 번에 내려앉는다. 그것이 이 연산의 성질이다.
넷째 자리가 어떻게 되는지는 셋째 자리와 아무 상관이 없다. 자리마다 따로,
그러나 같은 순간에 정해진다. 자리올림이 옆으로 번지는 덧셈과 갈리는 자리가
여기다 — 마스크에는 번질 것이 없다.

\`10101011\` 에 \`00001111\` 을 씌우면 아래 넉 자리만 남아 \`00001011\`,
곧 11 이다. 같은 값에 \`11110000\` 을 씌우면 위 넉 자리만 남아 \`10100000\`,
곧 160 이다.

## 덮개를 걷으면 그대로다

\`v & 0x0F\` 는 새 값을 내놓을 뿐 \`v\` 를 건드리지 않는다. 그림이 덮개를
걷어 원래 값을 다시 보이는 것은 그 때문이다. 마스크는 읽어 내는 도구이지
지우는 도구가 아니다.

## 자리는 제자리에 남는다

한 가지 더. 위 넉 자리를 골라내도 그 값은 \`10100000\`, 곧 160 이다. 우리가
알고 싶었던 "위 넉 자리의 값" 인 10 이 아니다. 마스크는 필요 없는 자리를
0 으로 덮을 뿐, 남은 자리를 옮겨 주지는 않는다. 값으로 읽으려면 오른쪽으로
넉 칸 밀어야 한다 — \`10100000 >> 4\` 는 \`00001010\`, 곧 10 이다.

그래서 자리 골라내기는 대개 둘이 짝을 이룬다. 마스크로 **가리고**, 시프트로
**옮긴다.** 그림은 앞의 절반만 보이고 있다.
`;
