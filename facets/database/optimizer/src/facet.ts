const scan = (id: string, table: string): PlanNode => ({ id, op: 'Seq Scan', detail: table, table, children: [] });
const filterCustomers = (): PlanNode => ({
  id: 'filter',
  op: 'Filter',
  detail: 'c.id <= {k}',
  filterColumn: 'c.id',
  children: [scan('scan-customers', 'customers')],
});
const project = (child: PlanNode): PlanNode => ({
  id: 'project',
  op: 'Project',
  detail: 'c.name, o.item',
  columns: ['c.name', 'o.item'],
  children: [child],
});

