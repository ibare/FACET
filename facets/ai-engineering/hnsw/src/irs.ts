/**
 * HNSW facet IR — **비워 둔다.** 이 완제품에는 코드 패널이 없다.
 *
 * ── 왜 비었는가
 *
 * 이 화면의 주장은 셈이 아니라 **층의 깊이와 확실함의 관계**다. 탐욕 걷기를 IR 로
 * 펴면 코드 패널이 말하는 것이 "층이 무엇을 사는가" 가 아니라 "이 걷기가 어떻게
 * 도는가" 가 된다.
 *
 *   - 걷기의 알맹이는 **이웃을 훑어 가장 가까운 것을 고르는 반복문** 하나다.
 *     여섯 언어로 갈라 놓아도 여섯 다 같은 모양의 `for` 안에 `if (d < best)` 가
 *     들어 있을 뿐이라, 언어가 갈리는 자리에서 배울 것이 없다.
 *   - 그 위에 **층을 내려오는 바깥 반복문**이 하나 더 얹힌다. 두 겹 반복문을
 *     읽는 동안 독자가 보는 것은 층의 값이 아니라 색인 변수 둘이다.
 *
 * 무엇보다 이 화면이 말하려는 것은 **한 걸음이 어떻게 도는가가 아니라 여섯
 * 걸음의 끝이 어디에 모이는가**다. 그것은 코드의 성질이 아니라 데이터와 층
 * 구조의 성질이라, 코드 패널로는 보이지 않는다. `tsne` 가 퍼플렉시티 손잡이로
 * 논증을 지고 IR 을 비운 것과 같은 판단이다.
 *
 * ── 그러면 이 완제품은 무엇으로 완제품인가
 *
 * **손잡이가 논증을 진다.** 층 수를 1 · 2 · 3 · 4 로 옮기는 것 자체가 주장이다 —
 * 한 층뿐이면 여섯 중 하나만 맞히고 다섯은 국소에 갇혀 엉뚱한 데서 멎는데,
 * 층을 셋까지 쌓으면 여섯이 전부 같은 답에 닿는다. 그러면서 본 점은 5.67 에서
 * 11.00 으로 **늘어난다.** 값을 치르고 확실함을 사는 것이고, 그 맞바꿈은 층
 * 수를 직접 돌려 봐야 손에 잡힌다.
 *
 * 그리고 조각 둘이 따로 말한 것을 여기서 잇는다 — `neighborsLinkedAhead` 가
 * 한 층에서 이웃을 따라 걷는 일을, `coarseThenFine` 이 위층에서 내려오며 자리를
 * 물려주는 일을 고정된 진입점 하나로 말하고 멈췄다. 이 화면은 진입점 여섯에서
 * 한꺼번에 걸어, 얕으면 갈리고 깊으면 모인다는 것을 한 장면에서 보인다.
 *
 * ── 뒤따르는 규약
 *
 * IR 이 없으므로 `facet.ts` 에 `code-view` 블록을 두지 않고, `algorithm.ts` 도
 * `phase` 이벤트를 발신하지 않는다. C3 은 all-or-none 이라 한쪽만 두면 안 된다.
 */

