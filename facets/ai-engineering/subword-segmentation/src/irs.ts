/**
 * 서브워드 분할 facet 의 IR — **비워 둔다.** 이 완제품에는 코드 패널이 없다.
 *
 * ── 왜 비었는가
 *
 * BPE 의 셈은 처음부터 끝까지 **새 배열을 짓는 일**이다. 그런데 IR 에는 배열을
 * 만드는 식이 없다 — `IRExpr` 는 `lit|var|index|len|binop|unop|call` 뿐이고
 * `IRStmt` 에도 배열을 짓는 문이 없다. `kind: 'list'` 는 **타입**에만 있어서,
 * 매개변수로 들어온 배열을 색인해 읽는 것만 된다.
 *
 *   - **짝 빈도표** 가 새 자료다. 낱말을 훑으며 `"<왼쪽> <오른쪽>"` 을 세는데,
 *     그 표는 맵이거나 배열이고 둘 다 IR 에 없다.
 *   - **분할 결과** 도 새 자료다. `[t, h, e, </w>]` 를 `[the</w>]` 로 접는 것은
 *     길이가 줄어드는 새 열을 만드는 일이라, 받은 배열을 읽는 것만으로는 안 된다.
 *
 * 우회해 만들 수는 있다 — 자리마다 "합쳐졌는가" 를 나타내는 표식 배열을 받아
 * 그 위에 덧쓰는 식으로. 그러나 그렇게 하면 코드 패널이 보이는 것이 BPE 가 아니라
 * **그 우회**가 된다. 독자는 알고리즘 대신 자리표 관리를 읽는다.
 *
 * `tsne` 가 같은 판단을 했고(거기서는 수치해석의 살림이 알고리즘을 덮었다),
 * 저장소의 완제품 194 종이 `irs.ts` 를 빈 배열로 둔 채 완제품이다.
 *
 * ── 그러면 이 완제품은 무엇으로 완제품인가
 *
 * **손잡이가 논증을 진다.** 병합 횟수를 0 · 12 · 24 · 36 · 44 로 옮기는 것 자체가
 * 주장이다 — 같은 문장이 조각 33 에서 7 로 단조로 줄어든다. 그리고 조각
 * `betweenLetterAndWord`(세 크기) · `spaceIsPartOfIt`(빈칸 표식) ·
 * `boundaryShift`(한 글자 차이)가 고정 데이터로 한 장면씩 따로 말한 것을,
 * 여기서는 독자가 손잡이를 돌리며 한 화면에서 잇는다.
 *
 * ── 뒤따르는 규약
 *
 * IR 이 없으므로 `facet.ts` 에 `code-view` 블록을 두지 않고, `algorithm.ts` 도
 * `phase` 이벤트를 발신하지 않는다. C3 은 all-or-none 이라 한쪽만 두면 안 된다.
 */

